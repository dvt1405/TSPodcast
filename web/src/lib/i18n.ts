const dictionaries: Record<Locale, Dictionary> = { vi, en };

export const locale: Locale = process.env.NEXT_PUBLIC_SITE_LOCALE === "en" ? "en" : "vi";

export function getDictionary(l: Locale = locale): Dictionary {
  return dictionaries[l];
}

export const t: Dictionary = dictionaries[locale];

/** BCP-47 tag for <html lang> and og:locale. */
export const htmlLang = locale === "vi" ? "vi" : "en";
export const ogLocale = locale === "vi" ? "vi_VN" : "en_US";

