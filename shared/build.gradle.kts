import org.jetbrains.kotlin.gradle.dsl.JvmTarget

/**
 * Turns JSON files that live elsewhere in the repo into Kotlin string constants, so that
 * Android and iOS read the very same file (a static framework carries no resources) and
 * nobody keeps a hand-made copy in `shared/`.
 *
 * Each file becomes `val <camelCaseName>: String` on [objectName]. Long files are split into
 * chunks because one JVM string constant is limited to 65535 bytes.
 */
abstract class GenerateJsonSourcesTask : DefaultTask() {
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.NAME_ONLY)
    abstract val jsonFiles: ConfigurableFileCollection

    @get:Input
    abstract val packageName: Property<String>

    @get:Input
    abstract val objectName: Property<String>

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val pkg = packageName.get()
        val dir = outputDir.get().asFile
        dir.deleteRecursively()
        val target = File(dir, pkg.replace('.', '/') + "/" + objectName.get() + ".kt")
        target.parentFile.mkdirs()

        val properties = jsonFiles.files.sortedBy { it.name }.joinToString("\n\n") { file ->
            val name = file.nameWithoutExtension
                .split('_', '-', ' ')
                .filter { it.isNotEmpty() }
                .mapIndexed { index, part ->
                    if (index == 0) part.replaceFirstChar { it.lowercase() }
                    else part.replaceFirstChar { it.uppercase() }
                }
                .joinToString("")
            val chunks = chunk(file.readText(Charsets.UTF_8))
                .joinToString(",\n") { "        \"" + escape(it) + "\"" }
            "    /** Generated from `${file.name}`. */\n" +
                "    val $name: String\n" +
                "        get() = arrayOf(\n$chunks,\n    ).joinToString(separator = \"\")"
        }
        target.writeText(
            "// Generated by :shared:${name}. Do not edit.\n" +
                "package $pkg\n\n" +
                "internal object ${objectName.get()} {\n$properties\n}\n"
        )
    }

    private fun chunk(text: String): List<String> {
        val result = mutableListOf<String>()
        var start = 0
        while (start < text.length) {
            var end = minOf(start + CHUNK_CHARS, text.length)
            // Never split a surrogate pair: half of one cannot be written as UTF-8.
            if (end < text.length && text[end - 1].isHighSurrogate()) end--
            result += text.substring(start, end)
            start = end
        }
        return result
    }

    private fun escape(text: String): String = buildString {
        text.forEach { c ->
            when (c) {
                '\\' -> append("\\\\")
                '"' -> append("\\\"")
                '$' -> append("\\$")
                '\n' -> append("\\n")
                '\r' -> append("\\r")
                '\t' -> append("\\t")
                else -> append(c)
            }
        }
    }

    private companion object {
        /** 4 000 chars is at most 12 000 UTF-8 bytes, far below the 65 535 byte limit. */
        const val CHUNK_CHARS = 4_000
    }
}

// Fallback data that Android ships as assets (features-spec §2, M0 §3.4): read from the same files.
val generateBundledAssets by tasks.registering(GenerateJsonSourcesTask::class) {
    jsonFiles.from(
        rootProject.file("coreApi/src/main/assets/categories.json"),
        rootProject.file("coreApi/src/main/assets/blacklist.json"),
    )
    packageName.set("tss.t.shared.generated")
    objectName.set("BundledAssets")
    outputDir.set(layout.buildDirectory.dir("generated/bundledAssets/commonMain/kotlin"))
}

// Real PodcastIndex payloads that the Android debug build uses, as test fixtures.
val generateTestFixtures by tasks.registering(GenerateJsonSourcesTask::class) {
    jsonFiles.from(
        rootProject.file("podcasts/src/debug/assets/Trending.json"),
        rootProject.file("podcasts/src/debug/assets/Episode.json"),
        rootProject.file("podcasts/src/debug/assets/LiveEpidsode.json"),
        rootProject.file("podcasts/src/debug/assets/RecentFeeds.json"),
        // Android's browser User-Agent constant, so SharedConstantsTest compares against the source.
        rootProject.file("sharedResources/src/main/java/tss/t/sharedresources/SharedConstants.kt"),
    )
    packageName.set("tss.t.shared.fixtures")
    objectName.set("Fixtures")
    outputDir.set(layout.buildDirectory.dir("generated/testFixtures/commonTest/kotlin"))
}

plugins {
    alias(libs.plugins.kotlin.multiplatform)
    alias(libs.plugins.android.kotlin.multiplatform.library)
    alias(libs.plugins.kotlin.serilization)
}

kotlin {
    androidLibrary {
        namespace = "tss.t.shared"
        compileSdk = libs.versions.compileSdk.get().toInt()
        minSdk = libs.versions.minSdk.get().toInt()

        // Host (JVM) unit tests run commonTest without a device: ./gradlew :shared:testAndroidHostTest
        withHostTestBuilder {}

        compilerOptions {
            jvmTarget.set(JvmTarget.JVM_11)
        }
    }

    listOf(
        iosArm64(),
        iosSimulatorArm64(),
    ).forEach { target ->
        target.binaries.framework {
            baseName = "Shared"
            isStatic = true
        }
    }

    sourceSets {
        commonMain {
            kotlin.srcDir(generateBundledAssets.map { it.outputDir })
        }
        commonTest {
            kotlin.srcDir(generateTestFixtures.map { it.outputDir })
        }
        commonMain.dependencies {
            implementation(libs.kotlinx.coroutines.core)
            implementation(libs.kotlinx.serialization.json)
            implementation(libs.ktor.client.core)
            implementation(libs.ktor.client.content.negotiation)
            implementation(libs.ktor.serialization.kotlinx.json)
            implementation(libs.okio)
        }
        androidMain.dependencies {
            implementation(libs.ktor.client.okhttp)
        }
        iosMain.dependencies {
            implementation(libs.ktor.client.darwin)
        }
        commonTest.dependencies {
            implementation(libs.kotlin.test)
            implementation(libs.kotlinx.coroutines.test)
            implementation(libs.ktor.client.mock)
        }
    }
}
