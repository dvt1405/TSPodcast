package tss.t.shared.storage

import androidx.room.ConstructedBy
import androidx.room.Database
import androidx.room.RoomDatabase
import androidx.room.RoomDatabaseConstructor
import androidx.room.TypeConverters
import androidx.sqlite.driver.bundled.BundledSQLiteDriver
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.IO

/**
 * The four DAOs the shared logic uses. [PodcastDatabase] in the app; in-memory fakes in
 * `commonTest`, where the Android host test has no `Context` to build Room with.
 */
interface PodcastDaos {
    fun podcastDao(): PodcastDao
    fun episodeDao(): EpisodeDao
    fun feedDao(): FeedDao
    fun favouriteDao(): FavouriteDao
}

/**
 * The iOS database (M4 §4.1): Android `PodcastDatabase` v6 without `RadioChannel` (D1). It is a
 * new database on a new platform, so it starts at [VERSION] 1 with no migration. The schema is
 * exported to `shared/schemas/` and committed.
 */
@Database(
    entities = [PodcastEntity::class, FeedEntity::class, EpisodeEntity::class, FavouriteEntity::class],
    version = PodcastDatabase.VERSION,
    exportSchema = true,
)
@TypeConverters(StorageConverters::class)
@ConstructedBy(PodcastDatabaseConstructor::class)
abstract class PodcastDatabase : RoomDatabase(), PodcastDaos {
    abstract override fun podcastDao(): PodcastDao
    abstract override fun episodeDao(): EpisodeDao
    abstract override fun feedDao(): FeedDao
    abstract override fun favouriteDao(): FavouriteDao

    companion object {
        const val VERSION = 1

        /** File name under Application Support (Android: `TSPodcastDatabase`). */
        const val FILE_NAME = "TSPodcastDatabase.db"
    }
}

/** Generated by Room for every target. */
@Suppress("KotlinNoActualForExpect", "NO_ACTUAL_FOR_EXPECT")
expect object PodcastDatabaseConstructor : RoomDatabaseConstructor<PodcastDatabase> {
    override fun initialize(): PodcastDatabase
}

/** Bundled SQLite (same engine on every OS version) and queries on [Dispatchers.IO]. */
internal fun RoomDatabase.Builder<PodcastDatabase>.buildPodcastDatabase(): PodcastDatabase =
    setDriver(BundledSQLiteDriver())
        .setQueryCoroutineContext(Dispatchers.IO)
        .build()

/**
 * Opens (creating when missing) the database file at [path]. iOS only: Android keeps its own
 * Room database in `:core` and does not use `shared` (owner decision).
 */
expect fun openPodcastDatabase(path: String): PodcastDatabase
