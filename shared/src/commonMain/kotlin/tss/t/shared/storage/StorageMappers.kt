/*
 * API model <-> Room row. Where a column is NOT NULL on Android but optional in the API, the row
 * gets the value Android's Gson model would have held: `Podcast.feedId` falls back to the podcast
 * id (every PodcastIndex podcast id is its feed id), `Episode.feedItunesId` to 0.
 */

internal fun Podcast.toEntity(cachedAt: Long): PodcastEntity = PodcastEntity(
    categories = categories,
    dateCrawled = dateCrawled,
    datePublished = datePublished,
    datePublishedPretty = datePublishedPretty,
    enclosureLength = enclosureLength,
    enclosureType = enclosureType,
    enclosureUrl = enclosureUrl,
    explicit = explicit,
    feedId = feedId ?: id,
    feedImage = feedImage,
    feedItunesId = feedItunesId,
    feedLanguage = feedLanguage,
    feedTitle = feedTitle,
    guid = guid,
    id = id,
    image = image,
    link = link,
    title = title,
    description = description,
    cachedAt = cachedAt,
)

