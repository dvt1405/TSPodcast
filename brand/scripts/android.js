// Generates the Android launcher / splash / notification resources from the mark geometry.
//   drawable/ic_launcher_background.xml   gradient, 108dp
//   drawable/ic_launcher_foreground.xml   white mark + coral dot, inside the 66dp safe zone
//   drawable/ic_launcher_monochrome.xml   single-colour mark for Android 13 themed icons
//   drawable/ic_splash_icon.xml           Android 12+ splash icon (288dp canvas, 192dp circle)
//   drawable/ic_stat_tspodcast.xml        24dp white status-bar silhouette
//   mipmap-anydpi-v26/ic_launcher(_round).xml
//   mipmap-<density>/ic_launcher(_round).png  legacy icons (API 24–25)
//   app/src/main/ic_launcher-playstore.png    512×512
'use strict';
const fs = require('fs');
const path = require('path');
const L = require('./lib');
const { PALETTE: P, MARK } = L;

const RES = path.join(L.ROOT, 'app', 'src', 'main', 'res');
const argb = (hex) => `#FF${hex.replace('#', '').toUpperCase()}`;
const HEADER = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by brand/scripts/android.js — edit the generator, not this file. -->\n';

/**
 * Vector group drawing the mark so its bbox is centred in a `canvas`-dp square at `width` dp wide.
 * opts.t lets the status-bar icon use a shorter crossbar so the dot keeps a visible gap at 24dp.
 */
function markGroup(canvas, width, { line, dot, t = MARK.t, indent = '    ' }) {
  const b = MARK.bbox;
  const k = width / b.w;
  const tx = canvas / 2 - (b.x + b.w / 2) * k;
  const ty = canvas / 2 - (b.y + b.h / 2) * k;
  const i = indent;
  return `${i}<group\n${i}    android:scaleX="${L.r(k, 5)}"\n${i}    android:scaleY="${L.r(k, 5)}"\n` +
    `${i}    android:translateX="${L.r(tx)}"\n${i}    android:translateY="${L.r(ty)}">\n` +
    `${i}    <!-- T + S: one 14-unit stroke on a 100-unit grid -->\n` +
    `${i}    <path\n${i}        android:pathData="${t} ${MARK.s}"\n` +
    `${i}        android:strokeWidth="${MARK.stroke}"\n${i}        android:strokeColor="${line}"\n` +
    `${i}        android:strokeLineCap="round"\n${i}        android:strokeLineJoin="round" />\n` +
    `${i}    <!-- the on-air dot -->\n` +
    `${i}    <path\n${i}        android:fillColor="${dot}"\n` +
    `${i}        android:pathData="M${MARK.dot.cx - MARK.dot.r},${MARK.dot.cy} a${MARK.dot.r},${MARK.dot.r} 0 1,0 ${MARK.dot.r * 2},0 a${MARK.dot.r},${MARK.dot.r} 0 1,0 -${MARK.dot.r * 2},0z" />\n` +
    `${i}</group>\n`;
}

function vector(sizeDp, viewport, body) {
  return HEADER +
    `<vector xmlns:android="http://schemas.android.com/apk/res/android"\n` +
    `    android:width="${sizeDp}dp"\n    android:height="${sizeDp}dp"\n` +
    `    android:viewportWidth="${viewport}"\n    android:viewportHeight="${viewport}">\n${body}</vector>\n`;
}

// Launcher content width: 48dp of the 108dp canvas -> bbox diagonal ≈ 62dp, inside the 66dp safe circle.
const FG_WIDTH = 48;

const files = {
  'drawable/ic_launcher_background.xml': HEADER +
    `<vector xmlns:android="http://schemas.android.com/apk/res/android"\n` +
    `    xmlns:aapt="http://schemas.android.com/aapt"\n` +
    `    android:width="108dp"\n    android:height="108dp"\n    android:viewportWidth="108"\n    android:viewportHeight="108">\n` +
    `    <path android:pathData="M0,0h108v108h-108z">\n` +
    `        <aapt:attr name="android:fillColor">\n` +
    `            <gradient\n                android:type="linear"\n                android:startX="0"\n                android:startY="0"\n                android:endX="108"\n                android:endY="108">\n` +
    `                <item android:offset="0" android:color="${argb(P.bright)}" />\n` +
    `                <item android:offset="1" android:color="${argb(P.blue)}" />\n` +
    `            </gradient>\n        </aapt:attr>\n    </path>\n</vector>\n`,
  'drawable/ic_launcher_foreground.xml': vector(108, 108, markGroup(108, FG_WIDTH, { line: '#FFFFFFFF', dot: argb(P.coral) })),
  'drawable/ic_launcher_monochrome.xml': vector(108, 108, markGroup(108, FG_WIDTH, { line: '#FFFFFFFF', dot: '#FFFFFFFF' })),
  // Splash (API 31+): no icon background, so content must sit in the central 192dp circle of 288dp.
  'drawable/ic_splash_icon.xml': vector(288, 288, markGroup(288, 140, { line: '#FFFFFFFF', dot: argb(P.coral) })),
  'drawable/ic_stat_tspodcast.xml': vector(24, 24, markGroup(24, 21, { line: '#FFFFFFFF', dot: '#FFFFFFFF', t: 'M14,24 H67 M31,24 V84' })),
};
const adaptive = HEADER +
  `<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n` +
  `    <background android:drawable="@drawable/ic_launcher_background" />\n` +
  `    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n` +
  `    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n` +
  `</adaptive-icon>\n`;
files['mipmap-anydpi-v26/ic_launcher.xml'] = adaptive;
files['mipmap-anydpi-v26/ic_launcher_round.xml'] = adaptive;

// Legacy launcher PNGs: same art as the adaptive icon, pre-masked (square-ish + round).
function legacySvg(round) {
  const S = 192; const inset = 8; const s = S - inset * 2;
  const shape = round
    ? `<circle cx="${S / 2}" cy="${S / 2}" r="${s / 2}" fill="url(#tsg)"/>`
    : `<rect x="${inset}" y="${inset}" width="${s}" height="${s}" rx="${s * 0.225}" fill="url(#tsg)"/>`;
  // same proportion as the adaptive foreground (48/108 of the full canvas = 48/72 of the visible icon)
  const fill = round ? 0.58 : 0.62;
  return L.svgDoc(S, S, shape + L.markCentered(inset, inset, s, fill, { line: P.white, dot: P.coral }), { defs: L.gradientDef('tsg') });
}
const DENSITIES = { mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 };

async function main() {
  for (const [rel, xml] of Object.entries(files)) L.writeText(path.join(RES, rel), xml);
  // old artwork that the new resources replace (the webp foreground mipmaps and the v24 Android-robot drawable)
  const stale = ['drawable-v24/ic_launcher_foreground.xml'];
  for (const d of Object.keys(DENSITIES)) stale.push(`mipmap-${d}/ic_launcher_foreground.webp`, `mipmap-${d}/ic_launcher.webp`, `mipmap-${d}/ic_launcher_round.webp`);
  for (const rel of stale) { const p = path.join(RES, rel); if (fs.existsSync(p)) fs.rmSync(p); }
  const v24 = path.join(RES, 'drawable-v24'); if (fs.existsSync(v24) && !fs.readdirSync(v24).length) fs.rmdirSync(v24);

  for (const [d, px] of Object.entries(DENSITIES)) {
    await L.render(legacySvg(false), path.join(RES, `mipmap-${d}`, 'ic_launcher.png'), px);
    await L.render(legacySvg(true), path.join(RES, `mipmap-${d}`, 'ic_launcher_round.png'), px);
  }
  // Play Store listing icon: full-bleed square, Play applies its own mask.
  const { tile } = require('./logo');
  const play = L.svgDoc(512, 512, tile(0, 0, 512, { rounded: false, fill: 0.62 }), { defs: L.gradientDef('tsg') });
  await L.render(play, path.join(L.ROOT, 'app', 'src', 'main', 'ic_launcher-playstore.png'), 512);

  // Preview: how the adaptive layers look under common masks + themed + status bar (for review only)
  await preview();
  console.log('android: done');
}

/** Renders the vector drawables back to PNG via an SVG translation, to eyeball the real resources. */
function vectorToSvgBody(xml) {
  // translate the subset we emit (group transform + paths, fill or stroke)
  const g = xml.match(/android:scaleX="([\d.]+)"[\s\S]*?android:translateX="([-\d.]+)"[\s\S]*?android:translateY="([-\d.]+)"/);
  const paths = [...xml.matchAll(/<path([\s\S]*?)\/>/g)].map((m) => {
    const a = (n) => (m[1].match(new RegExp(`android:${n}="([^"]+)"`)) || [])[1];
    const col = (c) => (c ? `#${c.slice(3)}` : 'none');
    return `<path d="${a('pathData')}" fill="${col(a('fillColor'))}" stroke="${col(a('strokeColor'))}" stroke-width="${a('strokeWidth') || 0}" stroke-linecap="round" stroke-linejoin="round"/>`;
  }).join('');
  return `<g transform="translate(${g[2]} ${g[3]}) scale(${g[1]})">${paths}</g>`;
}
async function preview() {
  const fg = vectorToSvgBody(files['drawable/ic_launcher_foreground.xml']);
  const mono = vectorToSvgBody(files['drawable/ic_launcher_monochrome.xml']);
  const stat = vectorToSvgBody(files['drawable/ic_stat_tspodcast.xml']);
  const bg = `<rect width="108" height="108" fill="url(#tsg)"/>`;
  const masks = {
    circle: '<circle cx="54" cy="54" r="36"/>',
    squircle: '<rect x="18" y="18" width="72" height="72" rx="20"/>',
    teardrop: '<path d="M54,18 H90 V54 A36,36 0 1 1 54,18 Z"/>',
  };
  let defs = L.gradientDef('tsg', 0, 0, 1, 1);
  let body = `<rect width="1200" height="420" fill="#ECEFF5"/><rect x="0" y="210" width="1200" height="210" fill="#121318"/>`;
  let x = 20;
  for (const [n, m] of Object.entries(masks)) {
    defs += `<clipPath id="m-${n}">${m}</clipPath>`;
    for (const [row, y] of [[0, 20], [1, 230]]) {
      body += `<g transform="translate(${x - 18 * 2.2} ${y - 18 * 2.2}) scale(2.2)"><g clip-path="url(#m-${n})">${bg}${fg}</g></g>`;
    }
    x += 190;
  }
  // safe-zone overlay
  body += `<g transform="translate(${x - 18 * 2.2} ${20 - 18 * 2.2}) scale(2.2)"><rect width="108" height="108" fill="url(#tsg)" opacity=".35"/>${fg}<circle cx="54" cy="54" r="33" fill="none" stroke="${P.coral}" stroke-width=".6"/><rect x="0.3" y="0.3" width="107.4" height="107.4" fill="none" stroke="#000" stroke-width=".6"/></g>`;
  // themed icon (Android 13): tinted bg + mono
  body += `<g transform="translate(${x - 18 * 2.2} ${230 - 18 * 2.2}) scale(2.2)"><g clip-path="url(#m-circle)"><rect width="108" height="108" fill="#D7E3FF"/><g style="fill:#1A3D8F;stroke:#1A3D8F">${mono.replace(/(fill|stroke)="#FFFFFF"/g, '$1="#1A3D8F"')}</g></g></g>`;
  x += 190 + 20;
  // status bar silhouettes at 24dp × 1/2/3x
  let sx = x;
  for (const s of [24, 48, 72]) { body += `<g transform="translate(${sx} 300) scale(${s / 24})">${stat}</g>`; sx += s + 20; }
  body += `<g transform="translate(${x} 60)">` + [48, 72, 96].map((s, i) => `<g transform="translate(${[0, 60, 145][i]} 0)">${L.markCentered(0, 0, s, 1, { line: P.ink, dot: P.ink }).replace(/.*/, (q) => q)}</g>`).join('') + `</g>`;
  const svg = L.svgDoc(1200, 420, body, { defs });
  await L.render(svg, path.join(L.BRAND, 'android', 'android-icon-preview.png'), 1200);
}

